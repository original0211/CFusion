// CFusion P4: assemble the Cloudflare Workers deployment directory.
//
// Unlike build-vercel.mjs this intentionally uses only Node built-ins:
// the panel has no installed bundler dependency in a clean checkout, and
// Wrangler performs the final module bundling itself (including node:*
// imports under nodejs_compat). This script's job is the part Wrangler
// cannot do for the panel: embed the filesystem assets that server.mjs
// and singbox.mjs normally read from disk.
//
// Output (default panel/cloudflare/dist, must be empty or non-existent):
//   worker.mjs       entry copied from panel/cloudflare/worker.mjs
//   cf-assets.mjs    generated text assets + base64 sing-box rules gzip
//   src/*.mjs        runtime modules copied from panel/src (no tests/tools)
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

const srcRoot = fileURLToPath(new URL('../', import.meta.url)); // panel/src
const panelRoot = resolve(srcRoot, '..'); // panel
const cloudflareRoot = join(panelRoot, 'cloudflare');
const destination = resolve(process.argv[2] || join(cloudflareRoot, 'dist'));

await mkdir(destination, { recursive: true });
if ((await readdir(destination)).length) throw new Error('输出目录必须为空，避免把旧文件或凭据带进部署包');
await mkdir(join(destination, 'src'));

const textAsset = async name => readFile(join(srcRoot, name), 'utf8');
const assets = {
  theme: await textAsset('theme.css'),
  landing: await textAsset('index.html'),
  bridge: await textAsset('bridge.js'),
  rulesLicense: (await textAsset('singbox-rules.NOTICE.md')) + '\n' + (await textAsset('singbox-rules.LICENSE')),
};
const rulesGzBase64 = (await readFile(join(srcRoot, 'singbox-rules.json.gz'))).toString('base64');

await writeFile(
  join(destination, 'cf-assets.mjs'),
  '// Generated by src/tools/build-cloudflare.mjs. Do not edit by hand.\n' +
  'export const assets = ' + JSON.stringify(assets) + ';\n' +
  'export const singboxRulesGzBase64 = ' + JSON.stringify(rulesGzBase64) + ';\n',
);

// Runtime modules only: the loop is over panel/src files, so test/ and
// tools/ subdirectories are naturally excluded.
for (const entry of await readdir(srcRoot, { withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.mjs')) continue;
  await copyFile(join(srcRoot, entry.name), join(destination, 'src', entry.name));
}

await copyFile(join(cloudflareRoot, 'worker.mjs'), join(destination, 'worker.mjs'));
console.log('Cloudflare 部署目录已生成：' + destination);
